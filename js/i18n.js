function enFragments(s){
  let out = s;
  for(const [re, to] of EN_FRAGMENTS) out = out.replace(re, to);
  return out === s ? null : out;
}

const LOCALIZE_ATTRS = ['title', 'aria-label', 'placeholder', 'alt'];

function localize(root){
  if(!isEN() || !root) return;
  const walk = document.createTreeWalker(root, NodeFilter.SHOW_TEXT, {
    acceptNode: n => (n.parentElement && /^(SCRIPT|STYLE)$/.test(n.parentElement.tagName))
      ? NodeFilter.FILTER_REJECT : NodeFilter.FILTER_ACCEPT
  });
  const seen = [];
  for(let n = walk.nextNode(); n; n = walk.nextNode()) seen.push(n);
  for(const n of seen){
    const raw = n.nodeValue;
    const out = toEn(raw) ?? enFragments(raw.trim().replace(/\s+/g, ' '));
    if(out == null) continue;
    // keep whatever spacing sat around the phrase
    const [, before, , after] = n.nodeValue.match(/^(\s*)([\s\S]*?)(\s*)$/);
    n.nodeValue = before + out + after;
  }
  const els = root.querySelectorAll ? root.querySelectorAll('*') : [];
  for(const el of els){
    for(const a of LOCALIZE_ATTRS){
      const v = el.getAttribute && el.getAttribute(a);
      if(!v) continue;
      const out = toEn(v) ?? enFragments(v);
      if(out != null) el.setAttribute(a, out);
    }
  }
}


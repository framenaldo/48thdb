function toEn(s){
  const key = s.trim().replace(/\s+/g, ' ');
  if(!key) return null;
  if(EN[key] != null) return EN[key];
  for(const [re, out] of EN_PATTERNS){
    const m = key.match(re);
    if(!m) continue;
    /* A pattern may match the shape but decline the string — the name-pair rule
       only speaks for names it knows — so keep looking rather than give up. */
    const hit = typeof out === 'function' ? out(m) : out;
    if(hit != null) return hit;
  }
  return null;
}

